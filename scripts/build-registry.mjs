// Generates apps/registry.json and apps/registry.js from every apps/<id>/manifest.json.
// Both files are generated: never edit them by hand, never commit them.
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { APPS_DIR, appIds, readManifest } from './lib.mjs';

const ids = await appIds();
const registry = [];
let bad = 0;
for (const id of ids) {
  const { manifest, errors } = await readManifest(id);
  if (errors.length) {
    bad++;
    console.warn(`skipping apps/${id}: ${errors[0]}${errors.length > 1 ? ` (+${errors.length - 1} more, run npm run check)` : ''}`);
    continue;
  }
  registry.push(manifest);
}
registry.sort((a, b) => (a.added || '').localeCompare(b.added || '') || a.name.localeCompare(b.name));

/* ---------- write ---------- */
const out = async (name, global, data) => {
  const json = JSON.stringify(data, null, 2);
  await writeFile(join(APPS_DIR, name + '.json'), json + '\n');
  await writeFile(join(APPS_DIR, name + '.js'), `// Generated by scripts/build-registry.mjs. Do not edit.\nwindow.${global} = ${json};\n`);
};
await out('registry', 'KIDVO_REGISTRY', registry);
console.log(`registry: ${registry.length} app(s)${bad ? `, ${bad} skipped` : ''}`);
